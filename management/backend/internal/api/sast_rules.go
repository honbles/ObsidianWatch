func init() {
	SASTRules = append(SASTRules, owaspExtendedRules...)
}

// runSASTRules runs all applicable SAST rules against a single file's content.
// Returns one finding per rule per file (deduplicated at rule level).
func runSASTRules(repo, filePath, content string) []SASTFinding {
	var findings []SASTFinding
	lines := strings.Split(content, "\n")

	for _, rule := range SASTRules {
		if !rule.FilePat.MatchString(filePath) {
			continue
		}
		for lineNo, line := range lines {
			if rule.Pattern.MatchString(line) {
				snippet := strings.TrimSpace(line)
				if len(snippet) > 120 {
					snippet = snippet[:120] + "…"
				}
				findings = append(findings, SASTFinding{
					RuleID:   rule.ID,
					Severity: rule.Severity,
					CWE:      rule.CWE,
					OWASP:    rule.OWASP,
					Title:    rule.Title,
					Detail:   rule.Detail,
					Fix:      rule.Fix,
					Repo:     repo,
					File:     filePath,
					Line:     lineNo + 1,
					Snippet:  snippet,
					Engine:   "builtin",
				})
				break // one finding per rule per file
			}
		}
	}
	return findings
}
